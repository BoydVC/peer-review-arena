"""Render a review+chair transcript to readable markdown."""
from __future__ import annotations

from typing import Any


def render_review_md(bundle: dict[str, Any]) -> str:
    review = bundle["review"]
    chair = bundle["chair"]
    lines: list[str] = []
    lines.append(f"# Peer Review — {review['title']}")
    lines.append("")
    lines.append(f"- **Draft id:** `{review['draft_id']}`")
    lines.append(f"- **Source:** {review['source']}")
    lines.append(f"- **Kind:** `{review['kind']}`")
    lines.append(f"- **Reviewed at:** {review['reviewed_at']} (America/New_York box clock)")
    lines.append(
        f"- **Stats:** {review['draft_stats']['lines']} lines · "
        f"{review['draft_stats']['words']} words · "
        f"{review['draft_stats']['unique_urls']} urls"
    )
    lines.append(
        f"- **Chair verdict:** **{chair['verdict']}** "
        f"(risk={chair['risk_score']}, adjusted={chair['adjusted_score']})"
    )
    lines.append("")
    lines.append(chair["summary"])
    lines.append("")

    lines.append("## Must-fix before ship")
    lines.append("")
    if not chair["must_fix_before_ship"]:
        lines.append("_None — no blocker/high findings._")
        lines.append("")
    else:
        for m in chair["must_fix_before_ship"]:
            lines.append(f"### [{m['severity'].upper()}] {m['claim']}")
            lines.append(f"- **Persona:** {m['persona_id']} · **id:** `{m['id']}`")
            if m.get("evidence"):
                lines.append(f"- **Evidence:** {m['evidence']}")
            lines.append(f"- **Fix:** {m['suggested_fix']}")
            lines.append("")

    lines.append("## Nice-to-haves")
    lines.append("")
    nice = chair.get("nice_to_haves") or []
    if not nice:
        lines.append("_None filed at medium/low._")
        lines.append("")
    else:
        for m in nice:
            lines.append(f"- **[{m['severity']}]** {m['claim']} — _{m['suggested_fix']}_ (`{m['id']}`)")
        lines.append("")

    lines.append("## Consensus table")
    lines.append("")
    lines.append("| Topic | Worst | Personas | Headline |")
    lines.append("|---|---|---|---|")
    for row in chair["consensus_table"]:
        heads = row["headline"].replace("|", "/")
        lines.append(
            f"| `{row['topic']}` | {row['worst_severity']} | "
            f"{row['persona_count']} ({', '.join(row['personas'])}) | {heads} |"
        )
    lines.append("")

    lines.append("## Disagreements")
    lines.append("")
    if not chair["disagreements"]:
        lines.append("_No multi-persona severity spreads._")
        lines.append("")
    else:
        for d in chair["disagreements"]:
            lines.append(f"- **{d['topic']}**: {d['notes']}")
        lines.append("")

    lines.append("## Per-persona scoreboard")
    lines.append("")
    lines.append("| Persona | Findings | Blocker | High | Med | Low | Nit | Risk |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for p in chair["per_persona"]:
        lines.append(
            f"| {p['name']} | {p['finding_count']} | {p['blocker']} | {p['high']} | "
            f"{p['medium']} | {p['low']} | {p['nit']} | {p['risk_contribution']} |"
        )
    lines.append("")

    lines.append("## Full findings by persona")
    lines.append("")
    for p in review["personas"]:
        lines.append(f"### {p['name']} — {p['role']}")
        lines.append("")
        lines.append(f"_{p['summary']}_")
        lines.append("")
        for f in p["findings"]:
            lines.append(f"#### [{f['severity']}] {f['claim']}")
            lines.append(f"- **Topic:** `{f['topic']}` · **id:** `{f['id']}`")
            if f.get("evidence"):
                lines.append(f"- **Evidence:** {f['evidence']}")
            lines.append(f"- **Suggested fix:** {f['suggested_fix']}")
            lines.append("")
    lines.append("---")
    lines.append("_Generated by Peer Review Arena (TokenMax / Grok Bot weekly burn)._")
    lines.append("")
    return "\n".join(lines)
